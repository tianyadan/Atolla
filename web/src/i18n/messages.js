/** 简单插值：{name} → vars.name */
export function formatMessage(template, vars) {
  if (!vars || !template) return template || ''
  return String(template).replace(/\{(\w+)\}/g, (_, k) =>
    vars[k] == null ? `{${k}}` : String(vars[k]),
  )
}
