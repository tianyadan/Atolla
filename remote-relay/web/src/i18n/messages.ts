/** 简单插值 */
export function formatMessage(template: string, vars?: Record<string, string | number>): string {
  if (!vars || !template) return template || ''
  return String(template).replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] == null ? `{${k}}` : String(vars[k]),
  )
}
