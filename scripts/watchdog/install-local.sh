#!/usr/bin/env bash
# 安装并启用本机 LaunchAgent 后端守护。
# 关键：把探活/拉起脚本与二进制安装到 ~/.atolla/watchdog-local/，
# LaunchAgent 只执行家目录副本，避免仓库位于 Desktop/Documents 时出现
# 「Operation not permitted / exit 126」导致守护形同虚设。
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
LABEL="com.atolla.backend-watchdog"
PLIST_DIR="${HOME}/Library/LaunchAgents"
PLIST="${PLIST_DIR}/${LABEL}.plist"
STATE_DIR="${HOME}/.atolla/watchdog-local"
CHECK_SRC="$ROOT/scripts/watchdog/local-check.sh"
START_SRC="$ROOT/scripts/watchdog/start-backend.sh"
CHECK_DST="$STATE_DIR/local-check.sh"
START_DST="$STATE_DIR/start-backend.sh"
UID_NUM="$(id -u)"

chmod +x "$CHECK_SRC" "$START_SRC" 2>/dev/null || true
mkdir -p "$PLIST_DIR" "$STATE_DIR/bin"

# 记录仓库根，供家目录副本解析 DB/钩子路径
printf '%s\n' "$ROOT" >"$STATE_DIR/repo-root"

# 组装含 nvm / local 的 PATH，供 launchd 与 env.sh（否则找不到 claude/codex）
build_engine_path() {
  local dirs=() out="" d ver nvm="${NVM_DIR:-$HOME/.nvm}"
  dirs+=("$HOME/.local/bin" "$HOME/.bun/bin" "$HOME/.cargo/bin")
  if [ -f "$nvm/alias/default" ]; then
    ver="$(tr -d '[:space:]' <"$nvm/alias/default")"
    ver="${ver#v}"
    [ -n "$ver" ] && dirs+=("$nvm/versions/node/v${ver}/bin")
  fi
  for d in $(ls -1d "$nvm/versions/node"/v*/bin 2>/dev/null | sort -V -r); do
    dirs+=("$d")
  done
  dirs+=("/opt/homebrew/bin" "/usr/local/bin" "/usr/bin" "/bin" "/usr/sbin" "/sbin")
  for d in "${dirs[@]}"; do
    [ -d "$d" ] || continue
    case ":$out:" in
      *":$d:"*) continue ;;
    esac
    if [ -z "$out" ]; then out="$d"; else out="$out:$d"; fi
  done
  printf '%s' "$out"
}

# 安装时用当前 shell 的 command -v 固化绝对路径
resolve_engine_bin() {
  local bin="${1:-}"
  if [ -z "$bin" ]; then
    printf '%s' ""
    return
  fi
  if [[ "$bin" == /* ]]; then
    printf '%s' "$bin"
    return
  fi
  command -v "$bin" 2>/dev/null || printf '%s' "$bin"
}

ENGINE_PATH="$(build_engine_path)"
export PATH="${ENGINE_PATH}${PATH:+:$PATH}"

# 安装时可读仓库：把 .env 关键项落到家目录，降低 launchd 读 Desktop 失败概率
ENV_DST="$STATE_DIR/env.sh"
{
  echo "# generated by install-local.sh — do not edit by hand"
  echo "export ATOLLA_REPO_ROOT=\"$ROOT\""
  echo "export PATH=\"$ENGINE_PATH\${PATH:+:\$PATH}\""
  if [ -f "$ROOT/.env" ]; then
    # 只导出 AVATAR_ 前缀，避免把无关密钥塞进 launchd 环境文件时误伤
    # shellcheck disable=SC1091
    set -a
    . "$ROOT/.env"
    set +a
  fi
  # 裸名 claude 在 launchd 下常找不到；安装瞬间解析成绝对路径
  if [ -z "${AVATAR_CLAUDE_BIN:-}" ] || [ "${AVATAR_CLAUDE_BIN}" = "claude" ]; then
    AVATAR_CLAUDE_BIN="$(resolve_engine_bin claude)"
  else
    AVATAR_CLAUDE_BIN="$(resolve_engine_bin "$AVATAR_CLAUDE_BIN")"
  fi
  for k in AVATAR_ADDR AVATAR_BACKEND_PORT AVATAR_DB_DRIVER AVATAR_DB_DSN \
           AVATAR_CLAUDE_BIN AVATAR_ALLOWED_IPS AVATAR_WORKSPACE_ROOT \
           AVATAR_TIMEOUT_SEC AVATAR_PERMISSION_ENABLED AVATAR_PERMISSION_WAIT_SEC \
           AVATAR_REVIEW_TIMEOUT_SEC AVATAR_HOOK_BIN AVATAR_NOTIFY_SCRIPT \
           AVATAR_BARK_NOTIFY AVATAR_BACKEND_URL ATOLLA_LOCAL_WATCHDOG_GRACE_SEC; do
    eval "v=\${$k:-}"
    if [ -n "$v" ]; then
      # 简单转义双引号
      v_esc=$(printf '%s' "$v" | sed 's/\\/\\\\/g; s/"/\\"/g')
      echo "export $k=\"$v_esc\""
    fi
  done
  # sqlite 默认落到仓库 data（与手动 start.sh 一致）
  if [ -z "${AVATAR_DB_DSN:-}" ] && [ "${AVATAR_DB_DRIVER:-sqlite}" != "mysql" ]; then
    echo "export AVATAR_DB_DRIVER=\"sqlite\""
    echo "export AVATAR_DB_DSN=\"$ROOT/data/atolla.db\""
  fi
} >"$ENV_DST"

# 复制脚本到家目录（覆盖更新；不用 rm）
cp "$CHECK_SRC" "$CHECK_DST"
cp "$START_SRC" "$START_DST"
chmod +x "$CHECK_DST" "$START_DST"

# 安装阶段（用户态/管理台触发）有权读仓库：预编译二进制到家目录
echo "==> 预编译后端到 $STATE_DIR/bin/atolla"
mkdir -p "$ROOT/server/bin"
if [ ! -x "$ROOT/server/bin/avatar-hook" ]; then
  (cd "$ROOT/server" && go build -o bin/avatar-hook ./cmd/avatar-hook) 2>/dev/null || true
fi
(cd "$ROOT/server" && go build -o "$STATE_DIR/bin/atolla" .)
chmod +x "$STATE_DIR/bin/atolla"

# 清空旧的 launchd 错误日志（截断，不用 rm），避免 status 被历史 TCC 噪声误导
: >"$STATE_DIR/launchd.err.log"
: >"$STATE_DIR/launchd.out.log"
: >"$STATE_DIR/last-check"

cat >"$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${LABEL}</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>${CHECK_DST}</string>
  </array>
  <key>WorkingDirectory</key>
  <string>${STATE_DIR}</string>
  <key>StartInterval</key>
  <integer>60</integer>
  <key>RunAtLoad</key>
  <true/>
  <key>AbandonProcessGroup</key>
  <true/>
  <key>StandardOutPath</key>
  <string>${STATE_DIR}/launchd.out.log</string>
  <key>StandardErrorPath</key>
  <string>${STATE_DIR}/launchd.err.log</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>${ENGINE_PATH}</string>
    <key>HOME</key>
    <string>${HOME}</string>
    <key>ATOLLA_REPO_ROOT</key>
    <string>${ROOT}</string>
  </dict>
</dict>
</plist>
EOF

# 先卸再装，兼容新旧 launchctl
if launchctl print "gui/${UID_NUM}/${LABEL}" >/dev/null 2>&1; then
  launchctl bootout "gui/${UID_NUM}/${LABEL}" 2>/dev/null || true
elif launchctl list "$LABEL" >/dev/null 2>&1; then
  launchctl unload "$PLIST" 2>/dev/null || true
fi

if launchctl bootstrap "gui/${UID_NUM}" "$PLIST" 2>/dev/null; then
  launchctl enable "gui/${UID_NUM}/${LABEL}" 2>/dev/null || true
  launchctl kickstart -k "gui/${UID_NUM}/${LABEL}" 2>/dev/null || true
else
  launchctl load "$PLIST"
fi

echo "==> 已启用本机后端守护: $LABEL (grace=180s, interval=60s)"
echo "==> 探活脚本: $CHECK_DST"
echo "==> 仓库根: $ROOT"
